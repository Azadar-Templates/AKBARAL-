import { it } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

/* ============================================================
 * One shared layer, two products.
 *
 * The claim being tested is narrow and checkable: every token VALUE and every primitive
 * exists in exactly one file (design-system/, generated into each surface), neither
 * product's own stylesheet may re-declare one, and neither product may reach into the
 * other. Colors that are off-palette are counted and RATCHETED rather than pretend-absent:
 * the public sheet carries a second generation of violet tints and near-black scrims, and
 * swapping those hues is a brand change this brief forbids — so the test pins today's
 * number and fails if it grows, which is the only honest assertion available here.
 * ============================================================ */

const read = (file: string) => fs.readFileSync(path.resolve(file), 'utf8');
const SURFACES = {
  public: { sheet: 'public/styles.css', tokens: 'public/tokens.css', ui: 'public/akbaral-ui.css' },
  mission: { sheet: 'mission-dashboard/styles.css', tokens: 'mission-dashboard/tokens.css', ui: 'mission-dashboard/ui.css' },
} as const;
const PRIMITIVES = ['card', 'panel', 'btn', 'badge', 'banner', 'empty', 'field', 'table', 'modal', 'section-head'];
/** Off-palette color literals left in the public sheet (second-generation violet + scrim). */
const PUBLIC_OFF_PALETTE_ALLOWED = 197;

const TOKEN_TRIPLES = (() => {
  const tokens = read('public/tokens.css');
  const bases = new Set<string>();
  for (const match of tokens.matchAll(/:\s*(?:#([0-9a-fA-F]{6})\b|rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+))/g)) {
    if (match[1]) {
      const hex = match[1];
      bases.add([0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(','));
    } else bases.add([match[2], match[3], match[4]].join(','));
  }
  return bases;
})();
const SCALE_VALUES = (() => {
  const tokens = JSON.parse(read('design-system/tokens.json')) as { spacing: Record<string, unknown>; radius: Record<string, unknown> };
  const walk = (values: Record<string, unknown>, out: Record<string, string> = {}) => {
    for (const [name, value] of Object.entries(values)) {
      if (typeof value === 'object' && value !== null) { walk(value as Record<string, unknown>, out); continue; }
      const match = /^(\d+(?:\.\d+)?)px$/.exec(String(value).trim());
      if (match) out[`${parseFloat(match[1])}`] = `--${name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`;
    }
    return out;
  };
  return { spacing: walk(tokens.spacing), radius: walk(tokens.radius) };
})();

function declarations(css: string) {
  return [...css.matchAll(/^\s*(--[\w-]+)\s*:\s*([^;]+);/gm)].map((match) => `${match[1]}: ${match[2].trim()}`);
}
/** A CSS mask is drawn from an opaque stop; `#000`/`rgba(0,0,0)`/`rgba(255,255,255)`
 *  there are alphas in disguise, not palette colours, and no token exists for "opaque". */
const MASK_STOP = /^(?:#000|rgba?\(\s*(?:0|255)\s*,\s*(?:0|255)\s*,\s*(?:0|255)\s*(?:,\s*[\d.]+)?\))$/;
const MASK_LINE = /(?:-webkit-)?mask(?:-image|-size|-composite|-origin)?\s*:|background-clip\s*:/;
const COLOR_STOP = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)/g;

function colorLiterals(css: string) {
  const rows: Array<{ line: number; text: string; triple: string | null }> = [];
  css.split('\n').forEach((text, index) => {
    const masked = MASK_LINE.test(text);
    for (const stop of text.matchAll(COLOR_STOP)) {
      if (masked && MASK_STOP.test(stop[0])) continue;
      if (/^hsla?\(\s*var\(/.test(stop[0])) continue; // the sigil formula: hue supplied from the token
      const tripled = /^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)/.exec(stop[0]);
      rows.push({
        line: index + 1,
        text: text.trim().slice(0, 120),
        triple: tripled ? [tripled[1], tripled[2], tripled[3]].join(',') : null,
      });
    }
  });
  return rows;
}

it('the generated sheets are the same bytes on both surfaces, so there is one definition to change', () => {
  const surfaces = Object.entries(SURFACES);
  for (const [, files] of surfaces) {
    assert.ok(fs.existsSync(path.resolve(files.tokens)), `${files.tokens} is generated by design-system/build.mjs`);
    assert.ok(fs.existsSync(path.resolve(files.ui)), `${files.ui} is generated by design-system/build.mjs`);
  }
  const [publicTokens, missionTokens] = surfaces.map(([, files]) => declarations(read(files.tokens)));
  assert.ok(publicTokens.length > 120, `the token sheet is expected to hold the whole ramp, found ${publicTokens.length}`);
  assert.deepEqual(missionTokens, publicTokens, 'both surfaces must carry the same token values — one source of truth, two copies');
  const [publicUi, missionUi] = surfaces.map(([, files]) => read(files.ui));
  assert.equal(missionUi, publicUi, 'the primitive sheet is the same file in both products');
  assert.ok(publicTokens.join('').includes('--accent: #2f8348'), 'the green of the brand is the shared accent');
});

it('no product sheet re-declares a shared token or hides a colour inside a local one', () => {
  const shared = new Set(declarations(read('public/tokens.css')).map((row) => row.split(':')[0].trim()));
  assert.ok(shared.size > 120, `the token sheet is expected to hold the ramp, found ${shared.size} names`);
  for (const [, files] of Object.entries(SURFACES)) {
    const css = read(files.sheet);
    for (const row of declarations(css).filter((line) => line.startsWith('--'))) {
      const name = row.split(':')[0].trim();
      assert.ok(!shared.has(name), `${files.sheet} re-declares ${name}, which the shared sheet already defines — one definition means one place to change it`);
      assert.ok(!/#[0-9a-fA-F]{3,8}\b|rgba?\(|hsla?\(/.test(row), `${files.sheet} hides a colour literal inside ${name}: ${row} — colours are declared in design-system/tokens.json only`);
    }
  }
});

it('every primitive exists once in the shared sheet, and neither duplicate layer redefines it', () => {
  const shared = read('design-system/ui.css');
  const mission = read(SURFACES.mission.sheet);
  const facade = read('src/app/_components/ui/primitives.module.css');
  for (const primitive of PRIMITIVES) {
    assert.ok(new RegExp(`^\\.ak-${primitive}\\b[^{]*\\{`, 'm').test(shared), `.${primitive} must be defined in design-system/ui.css`);
    // The console used to carry its own copy of every one of these rules. Composition deltas
    // (a margin, a gap) are allowed to stay in its sheet; a second SURFACE is not.
    // Only the primitive's own selector counts: `.notification-badge` is a component of
    // this console, not a second `.badge`.
    for (const rule of [...mission.matchAll(new RegExp(`(?:^|[,{}])\\s*\\.${primitive}\\b[^{]*\\{([^}]*)\\}`, 'gm'))]) {
      const body = rule[1];
      // background-image + box-shadow are the glass MATERIAL (see the documented limit in
      // docs/DESIGN.md): the idiom is a masked gradient that stays physically duplicated, so
      // the assertion binds the SURFACE properties, which must not be redefined.
      for (const property of ['background', 'border', 'border-radius']) {
        assert.ok(!new RegExp(`(^|;)\\s*${property}\\s*:`).test(body),
          `the mission sheet redefines ${property} for .${primitive} — the shared sheet owns it: {${body.trim()}}`);
      }
    }
  }
  const blocks = [...facade.matchAll(/\.[\w-]+\s*\{([^}]*)\}/g)].map((match) => match[1]);
  assert.ok(blocks.length >= 8, `the facade is expected to expose the primitives, found ${blocks.length}`);
  let composed = 0;
  for (const block of blocks) {
    const rules = block.split(';').map((rule) => rule.trim()).filter(Boolean);
    assert.ok(rules.length >= 1, `an empty facade rule is dead weight: {${block.trim()}}`);
    const composing = rules.filter((rule) => /^composes:\s*ak-[\w-]+ from global$/.test(rule));
    if (composing.length) {
      composed += 1;
      // A base plus a variant is still composition; anything else it adds must be token geometry.
      for (const rule of rules) {
        if (rule.startsWith('composes:')) continue;
        assert.ok(/^(?:width|min-width|height|padding)\s*:\s*(?:0|var\(--[\w-]+\))$/.test(rule),
          `the facade composes a shared primitive and may only add token geometry, not ${rule} in {${block.trim()}}`);
      }
      continue;
    }
    // A rule with no composition is a layout utility (the shell measure, the visually-hidden
    // affordance). It may carry no surface of its own: colour, fill, radius and shadow exist
    // once, in design-system/ui.css, and are composed above — never re-declared here.
    for (const rule of rules) {
      const [property, value = ''] = rule.split(':');
      const name = property.trim();
      if (/^(?:color|background|background-color|border-radius|box-shadow|border)$/.test(name)) {
        assert.ok(/^\s*(?:0|none|transparent)\s*$/.test(value),
          `the facade may not define a surface of its own (${rule}) — compose the shared primitive instead: {${block.trim()}}`);
      }
    }
  }
  // The five that do not compose are the layout utilities (a shell measure, a visually-hidden
  // affordance) — no product component may restyle a primitive without composing it.
  assert.ok(composed / blocks.length >= 0.8, `the facade must be composition, not a second stylesheet: ${composed}/${blocks.length} rules compose a shared primitive`);
  assert.equal(facade.replace(/\/\*[\s\S]*?\*\//g, '').match(/#[0-9a-fA-F]{3,8}\b|rgba?\(/g)?.length ?? 0, 0, 'the facade carries no colour');
});

it('no literal colour sits outside the shared tokens beyond the ratcheted residual', () => {
  for (const [name, files] of Object.entries(SURFACES)) {
    const rows = colorLiterals(read(files.sheet));
    if (name === 'mission') {
      assert.deepEqual(rows, [], `the mission sheet must be literal-free, found ${rows.length}`);
      continue;
    }
    const off = rows.filter((row) => row.triple && !TOKEN_TRIPLES.has(row.triple));
    assert.ok(off.length <= PUBLIC_OFF_PALETTE_ALLOWED,
      `the public sheet gained off-palette colour literals (${off.length} > ${PUBLIC_OFF_PALETTE_ALLOWED}) — add a token instead of a new hue`);
    for (const row of rows) {
      assert.ok(!row.text.startsWith('--') || row.triple !== null, `a hex in a token declaration belongs in design-system/tokens.json: ${files.sheet}:${row.line}`);
    }
    assert.equal(rows.filter((row) => row.triple === null && !/mask/.test(row.text)).length, 0, 'a hex literal outside a mask is a bypass');
  }
});

it('no hardcoded spacing, radius, border or font-family bypasses a token that already says it', () => {
  const fontFamilies: string[] = [];
  const bypasses: string[] = [];
  for (const [, files] of Object.entries(SURFACES)) {
    read(files.sheet).split('\n').forEach((text, index) => {
      const line = `${files.sheet}:${index + 1}`;
      for (const match of text.matchAll(/font-family\s*:\s*([^;}]+)/g)) {
        const value = match[1].trim();
        if (!value.startsWith('var(') && value !== 'inherit') fontFamilies.push(`${line} ${value}`);
      }
      if (/@media|@supports|mask\s*:/.test(text)) return;
      for (const prop of ['padding', 'margin', 'gap', 'row-gap', 'column-gap', 'border-radius']) {
        const match = new RegExp(`(?<![-\\w])${prop}\\s*:\\s*([^;}]+)`).exec(text);
        if (!match) continue;
        for (const px of match[1].matchAll(/(?<![\w.-])(\d+(?:\.\d+)?)px(?![\w.])/g)) {
          const table = prop === 'border-radius' ? SCALE_VALUES.radius : SCALE_VALUES.spacing;
          const token = table[`${parseFloat(px[1])}`];
          // A value that is exactly a scale step has one definition already; anything else is a
          // one-off composition (a hairline, an optical nudge) with no token to name it.
          if (token) bypasses.push(`${line} ${prop}: ${px[0]} → var(${token})`);
        }
      }
      for (const match of text.matchAll(/border\s*:\s*(\d+(?:\.\d+)?)px/g)) {
        if (match[1] !== '1' && !/scrollbar/.test(text)) bypasses.push(`${line} border width ${match[0]} — the shared sheet defines --border-hairline and --border-strong only`);
      }
    });
  }
  assert.deepEqual(fontFamilies, [], 'a font-family literal would be a second font: ' + fontFamilies.slice(0, 3).join(' / '));
  assert.deepEqual(bypasses, [], 'literals that match a shared scale step must use the token: ' + bypasses.slice(0, 6).join(' / '));
});

it('both surfaces link the generated layer, and the public allow-list still serves it', () => {
  // This is the wiring that makes "one layer" more than a folder layout: a shell that stops
  // linking the sheet silently falls back to whatever its own stylesheet remembers.
  const layout = read('src/app/layout.tsx');
  assert.match(layout, /<link rel=\"stylesheet\" href=\"\/assets\/tokens\.css/, 'the public shell links the shared ramp');
  assert.match(layout, /<link rel=\"stylesheet\" href=\"\/assets\/akbaral-ui\.css/, 'the public shell links the shared primitives');
  const allowList = read('src/app/assets/[file]/route.ts');
  for (const served of ['app.js', 'styles.css', 'tokens.css', 'akbaral-ui.css']) {
    assert.ok(allowList.includes(`'${served}'`), `/assets/${served} must stay on the served allow-list`);
  }
  const mission = read('mission-dashboard/index.html');
  const refs = [...mission.matchAll(/(?:src|href)=\"([^\"]+)\"/g)].map((match) => match[1]);
  for (const href of ['/tokens.css', '/ui.css', '/styles.css', '/copy.js', '/app.js']) {
    assert.ok(refs.includes(href), `the console must load ${href}`);
  }
  assert.ok(refs.indexOf('/copy.js') < refs.indexOf('/app.js'), 'the dictionary loads before the code that reads it');
});

it('the two products stay separate: no shared stylesheet, no import, no name across the seam', () => {
  const own = ['index.html', 'app.js', 'styles.css', 'copy.js', 'service-worker.js', 'manifest.webmanifest'];
  const strip = (text: string) => text.replace(/\/\*[\s\S]*?\*\/|<!--[\s\S]*?-->/g, ' ');
  const mission = own.map((file) => [`mission-dashboard/${file}`, strip(read(`mission-dashboard/${file}`))] as const);
  for (const [file, text] of mission) {
    // The console may NAME the other product (the money panel explains that customer
    // payments live there); what it may never do is borrow its marks, its assets or its pages.
    assert.ok(!/\/brand\/|akbaral-logo|akbaral-icon|akbaral-ui|\/assets\//.test(text), `${file} must not read a public-surface brand asset`);
    assert.ok(!/<(img|link|script)[^>]*(\/brand\/|\/assets\/)/.test(text), `${file} must not load a public-surface asset tag`);
    assert.ok(!/from ['"]\.\.\/\.\.\/src|require\(['"]\.\.\/\.\.\/src/.test(text), `${file} must not import application source`);
  }
  const appFiles = fs.readdirSync(path.resolve('src/app/_components'), { recursive: true })
    .filter((entry) => String(entry).endsWith('.tsx') || String(entry).endsWith('.css'))
    .map((entry) => path.join('src/app/_components', String(entry)));
  for (const file of appFiles) {
    const text = read(file);
    assert.ok(!/mission-dashboard|\/copy\.js/.test(text), `${file} must not read the mission console's files`);
  }
  // The gateway is the one deliberate seam, and it is an owner-authenticated proxy, not a shared asset.
  const gateway = read('src/app/mission-gateway/[[...path]]/route.ts');
  assert.ok(gateway.includes('/mission-gateway/$2'), 'the gateway keeps rebasing the dashboard inside its own prefix');
});
